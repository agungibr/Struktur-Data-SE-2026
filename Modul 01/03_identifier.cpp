#include <iostream>
using namespace std;

int main() {
    // Identifier adalah nama untuk variabel, konstanta, fungsi, dan objek lain.
    int nilaiMahasiswa = 85;
    int nilai_akhir = 90;

    // C++ bersifat case-sensitive:
    int nilai = 10;
    int Nilai = 20;

    cout << "nilai       = " << nilai << endl;
    cout << "Nilai       = " << Nilai << endl;
    cout << "nilaiMahasiswa = " << nilaiMahasiswa << endl;
    cout << "nilai_akhir = " << nilai_akhir << endl;

    return 0;
}
