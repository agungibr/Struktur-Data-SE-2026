#include <iostream>
using namespace std;

int main() {
    char karakter = 'A';
    int bilanganBulat = 100;
    long bilanganPanjang = 1000000;
    float pecahan = 3.14f;
    double pecahanLebihPresisi = 3.1415926535;

    cout << "char   : " << karakter << endl;
    cout << "int    : " << bilanganBulat << endl;
    cout << "long   : " << bilanganPanjang << endl;
    cout << "float  : " << pecahan << endl;
    cout << "double : " << pecahanLebihPresisi << endl;

    return 0;
}
